// Chat sessions' runs in Workflow (loaded on demand by plans.js withChatRuns): a chat session is a plan
// (chat-<session>) run by the same runner. Runs shows its tasks × agents grid, usage and logs; Graph / List
// show the session's task graph or task rows. Retry, skip and new tasks stay in the Chat section.
import { $, esc, icon, loadCss, routeHash, short } from "../utils/dom.js";
import { server } from "../data/server.js";
import { CELL, RUN_STATUS, loadPlan, logButtons, planOf, releasePlanPin, runPicker, usageButton } from "./plans.js";
import { dockLog } from "./logview.js";
import { taskMenuApi } from "./task_menu_api.js";
import { mountGraph } from "./graph_view.js";
import { graphModel, money, statusInfo } from "../data/chat.js";

const sessions = new Map(); // project|sid -> {data, key, loading, error}
let graph = null, graphHost = null, cur = null; // cur: {ctx, project} of the last render, for the handlers

/** The chat session state (titles, graph, tasks), re-read when the run's units or status change. */
function session(ctx, project, s) {
  const sid = s.plan.chat.session, k = `${project}|${sid}`, e = sessions.get(k) || {};
  const key = JSON.stringify([s.plan.status, (s.units || []).map((u) => [u.id, u.status])]);
  sessions.set(k, e);
  if (e.key !== key && !e.loading) {
    e.loading = true;
    server.request(`/api/studio/projects/${encodeURIComponent(project)}/chat/sessions/${encodeURIComponent(sid)}`, { headers: { Accept: "application/json" } })
      .then(async (res) => { const body = await res.json().catch(() => null); if (!res.ok) throw new Error(body?.error?.message || `${res.status} ${res.statusText}`); e.data = body; e.error = null; })
      .catch((err) => { e.error = err.message; })
      .finally(() => { e.loading = false; e.key = key; ctx.update(); });
  }
  return e;
}

const chatHref = (ctx, project, sid) => routeHash(`chat/${sid}`, project, ctx.state.selectedTarget);
const title = (s) => s.plan.title || s.plan.chat.session;
const kindOf = (r) => r.values?.KIND || "task";

/** Runs: a chat session's run (tasks × agents). */
export function renderRun(box, ctx, project, s) {
  cur = { ctx, project };
  loadCss("css/lazy.css");
  const p = s.plan, sid = p.chat.session, e = session(ctx, project, s);
  const tasks = new Map((e.data?.tasks || []).map((t) => [t.row, t]));
  const rows = s.table?.rows || [];
  const label = (key) => { const row = rows.find((x) => x.key === key), kind = row ? kindOf(row) : "task";
    return tasks.get(key)?.task?.title || (kind !== "task" ? `${kind[0].toUpperCase()}${kind.slice(1)} ${row.values?.REQUEST || ""}` : key || ""); };
  const used = (s.table?.steps || []).filter((st) => rows.some((r) => (r.cells[st] || "skip") !== "skip"));
  const steps = used.length ? used : s.table?.steps || [];
  const tot = {};
  rows.forEach((r) => steps.forEach((st) => { const v = r.cells[st]; if (v && v !== "skip") tot[v] = (tot[v] || 0) + 1; }));
  const all = Object.values(tot).reduce((a, b) => a + b, 0), pct = all ? Math.round(((tot.done || 0) / all) * 100) : 0;
  const canAct = Boolean(server.session?.mutations_enabled), active = ["running", "paused", "interrupted"].includes(p.status);
  const t = s.agent_totals || {}, units = (s.units || []).slice().reverse();
  const r = s.runner || {};
  box.innerHTML = `
    <div class="sched-h">
      ${runPicker(ctx, s)}
      <span class="badge tone-${p.status === "running" ? "run" : p.status === "failed" ? "fail" : "muted"}">${icon("chat")}Chat · ${esc(RUN_STATUS[p.status] || p.status)}</span>
      <div class="plan-bar" title="${pct}% of task cells done"><i style="width:${pct}%"></i></div><span class="tabular small">${tot.done || 0}/${all}</span>
      <span class="grow"></span>
      <a class="btn sm primary" href="${esc(chatHref(ctx, project, sid))}">${icon("chat")} Open in Chat</a>
      ${canAct && p.status === "running" ? `<button class="btn sm" data-plan="pause" title="Pause: running tasks finish, nothing new starts">${icon("pause")} Pause</button>` : ""}
      ${canAct && active && p.status !== "running" ? `<button class="btn sm" data-plan="resume">${icon("play")} Resume</button>` : ""}
      ${(s.units || []).some((u) => u.usage || u.agent_usage) ? `<button class="btn sm" data-plan="usage">${icon("graph")} Usage</button>` : ""}
      <button class="btn sm" data-cr-log="${esc(p.id)}">${icon("log")} Runner log</button>
      ${canAct && active ? `<button class="btn sm danger" data-plan="cancel">${icon("stop")} Cancel</button>` : ""}
    </div>
    <p class="sched-meta muted small"><b>${esc(title(s))}</b> · tasks generated by the chat · concurrency ${esc(p.concurrency)} · ${esc(r.alive ? `runner ${r.pid} @ ${r.host}` : "no runner")}${Number.isFinite(t.total_cost_usd) ? ` · ${esc(money(t.total_cost_usd))}` : ""}${e.error ? ` · <span class="fail-t">${esc(e.error)}</span>` : ""}</p>
    <section class="sched-grid">
      <h4>Tasks × agents <span class="muted small">(click a cell: its log)</span></h4>
      <div class="grid-scroll" role="region" aria-label="Chat tasks by agents" tabindex="0"><table class="tbl plan-grid"><thead><tr><th>Task</th>${steps.map((st) => `<th><span class="mono">@${esc(st)}</span></th>`).join("")}</tr></thead><tbody>
        ${rows.map((row) => {
          return `<tr><td><b>${esc(label(row.key))}</b> <span class="mono small muted">${esc(row.key)}</span></td>${steps.map((st) => {
            const v = row.cells[st] || "skip", meta = CELL[v] || { label: v, mark: "?" };
            return `<td class="cell c-${esc(v)}" ${v === "skip" ? "" : `data-cr-cell="${esc(row.key)}" tabindex="0" role="button"`} title="${esc(`${meta.label}${v === "skip" ? "" : " · open its log"}`)}">${v === "running" ? icon("sync", "spin") : esc(meta.mark)}</td>`;
          }).join("")}</tr>`;
        }).join("") || `<tr><td colspan="${steps.length + 1}" class="muted">No tasks yet.</td></tr>`}
      </tbody></table></div>
    </section>
    <section class="sched-list"><h4>Attempts <span class="muted small">${units.length}</span></h4>
      <table class="tbl small ord"><tbody>${units.slice(0, 200).map((u) => `<tr class="c-${esc(u.status)}"><td><b>${esc(label(u.row || u.target))}</b> <span class="mono small muted">@${esc((u.steps || []).join(", "))}${u.model ? ` · ${esc(u.model)}` : ""}</span>${u.error ? `<div class="fail-t small ellip">${esc(String(u.error).slice(0, 80))}</div>` : ""}</td>
        <td>${esc(CELL[u.status]?.label || u.status || "")}</td><td class="tabular small">${u.finished && u.started ? esc(short((new Date(u.finished) - new Date(u.started)) / 1000)) : ""}</td>
        <td class="tabular small">${Number.isFinite(u.total_cost_usd) ? esc(money(u.total_cost_usd)) : ""}</td><td class="ord-a">${logButtons(project, u.log)}${usageButton(project, u)}</td></tr>`).join("") || '<tr><td class="muted">Nothing has run yet.</td></tr>'}</tbody></table>
    </section>`;
}

/** Graph / List with a chat run picked: the session's task graph or task rows, and a way back. */
export function renderPane(box, ctx, project, mode) {
  cur = { ctx, project };
  loadCss("css/chat.css");
  loadCss("css/lazy.css");
  const s = planOf(project), sid = s.plan.chat.session, e = session(ctx, project, s);
  const key = `${project}|${sid}|${mode}`;
  if (box.dataset.cr !== key || !box.querySelector(".cr-pane")) {
    box.dataset.cr = key;
    graph = graphHost = null;
    box.innerHTML = `<div class="cr-pane"><div class="callout info cr-banner" role="note">${icon("chat")}<span class="grow"><b>Chat session ${esc(title(s))}</b> — tasks generated by the chat</span>
      <button class="btn sm" data-cr-back>${icon("workflow")} Back to the workflow</button><a class="btn sm primary" href="${esc(chatHref(ctx, project, sid))}">${icon("chat")} Open in Chat</a></div>
      <div class="cr-body ${mode === "graph" ? "cr-graph" : ""}"></div></div>`;
  }
  const body = $(".cr-body", box), agents = e.data?.settings?.agents || {};
  if (!e.data) { body.innerHTML = `<p class="muted" role="status">${e.error ? esc(e.error) : "Loading the chat session…"}</p>`; return; }
  if (mode === "graph") {
    if (!graph || graphHost !== body) {
      graphHost = body;
      graph = mountGraph(body, { taskMenu: taskMenuApi({ project: () => project, sid: () => sid, state: () => e.data,
        refresh: async () => {
          const res = await server.request(`/api/studio/projects/${encodeURIComponent(project)}/chat/sessions/${encodeURIComponent(sid)}`);
          if (!res.ok) throw new Error(`Refresh: ${res.status}`);
          e.data = await res.json(); ctx.update();
        }, openLog: (rel) => dockLog(ctx, project, rel), files: () => { location.hash = chatHref(ctx, project, sid); } }), label: "Chat task graph", empty: "No tasks yet: they appear when the chat plans a request.",
        onOpen: () => { location.hash = chatHref(ctx, project, sid); } });
    }
    graph.update(graphModel(e.data.graph, agents));
    return;
  }
  const tasks = e.data.tasks || [];
  body.innerHTML = `<table class="tbl list-tbl"><thead><tr><th>Task</th><th>Owner</th><th>Status</th><th>Attempts</th><th>Cost</th></tr></thead><tbody>
    ${tasks.map((t) => {
      const info = statusInfo(t.status), kind = t.kind && t.kind !== "task" ? t.kind : "";
      return `<tr data-cr-task="${esc(t.row)}" tabindex="0" title="Open in Chat"><td><b>${esc(t.task?.title || (kind ? `${kind[0].toUpperCase()}${kind.slice(1)} ${t.request || ""}` : t.row))}</b> <span class="mono small muted">${esc(t.row)}</span></td>
        <td class="mono">@${esc(t.owner)}</td><td><span class="badge tone-${esc(info.tone)}">${icon(info.icon)}${esc(info.label)}</span></td>
        <td class="tabular">${esc(t.attempts ?? 0)}</td><td class="tabular">${esc(money(t.usage?.total_cost_usd))}</td></tr>`;
    }).join("") || '<tr><td colspan="5" class="muted">No tasks yet: they appear when the chat plans a request.</td></tr>'}</tbody></table>`;
}

document.addEventListener("click", (ev) => {
  const t = ev.target.closest?.("[data-cr-back], [data-cr-task], [data-cr-cell], [data-cr-log]");
  if (t && cur) act(t);
});
document.addEventListener("keydown", (ev) => {
  const t = (ev.key === "Enter" || ev.key === " ") && ev.target.closest?.("[data-cr-task], [data-cr-cell]");
  if (t && cur) { ev.preventDefault(); act(t); }
});

function act(t) {
  const { ctx, project } = cur, s = planOf(project);
  if (!s?.plan?.chat) return;
  if (t.matches("[data-cr-back]")) { releasePlanPin(project); loadPlan(ctx, project); return; }
  if (t.matches("[data-cr-task]")) { location.hash = chatHref(ctx, project, s.plan.chat.session); return; }
  if (t.matches("[data-cr-log]")) { dockLog(ctx, project, `.alfrd/plans/${s.plan.id}/runner.log`); return; }
  const u = (s.units || []).slice().reverse().find((x) => (x.rows || [x.row]).includes(t.dataset.crCell) && x.log);
  if (u) dockLog(ctx, project, u.log); else ctx.toast("No log yet for this task", "info");
}
